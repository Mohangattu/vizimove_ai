/**
 * Returns calibration evidence and local grounding notes for a zone.
 */
export function getCalibrationForZone(zoneId: string): CalibrationEvidence | undefined {
  return VIZAG_CALIBRATION_EVIDENCE.find((e) => e.zoneId === zoneId);
}

/**
 * Validates that all zones have corresponding calibration records.
 */
export function validateCalibrationCoverage(): {
  totalZones: number;
  calibratedCount: number;
  provisionalCount: number;
  isFullyCovered: boolean;
} {
  const totalZones = VIZAG_ZONES.length;
  const calibratedCount = VIZAG_CALIBRATION_EVIDENCE.filter((e) => e.calibrationStatus === 'VALIDATED').length;
  const provisionalCount = VIZAG_CALIBRATION_EVIDENCE.filter((e) => e.calibrationStatus === 'PROVISIONAL').length;

  return {
    totalZones,
    calibratedCount,
    provisionalCount,
    isFullyCovered: calibratedCount + provisionalCount === totalZones,
  };
}
