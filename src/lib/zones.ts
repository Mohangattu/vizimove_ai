/**
 * Great-circle distance between two geographic coordinates in kilometers (Haversine formula).
 */
export function calculateHaversineDistance(c1: GeoCoordinate, c2: GeoCoordinate): number {
  const R = 6371; // Earth radius in km
  const dLat = ((c2.lat - c1.lat) * Math.PI) / 180;
  const dLng = ((c2.lng - c1.lng) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((c1.lat * Math.PI) / 180) *
      Math.cos((c2.lat * Math.PI) / 180) *
      Math.sin(dLng / 2) *
      Math.sin(dLng / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 100) / 100;
}

/**
 * Estimates driving travel time in minutes based on real distance and average Vizag arterial speeds (~28 km/h).
 */
export function estimateTravelTimeMinutes(distanceKm: number, peakHour: boolean = false): number {
  const speedKmh = peakHour ? 20 : 28;
  const hours = distanceKm / speedKmh;
  const minutes = hours * 60;
  return Math.max(4, Math.round(minutes + 3));
}

export function getZoneById(id: string): ZoneRecord | undefined {
  return VIZAG_ZONES.find((z) => z.id === id);
}

export function getAllZones(): ZoneRecord[] {
  return VIZAG_ZONES;
}

/**
 * Precomputes symmetric distance matrix between all Visakhapatnam zones.
 */
export function getDistanceMatrix(): Record<string, Record<string, number>> {
  const matrix: Record<string, Record<string, number>> = {};
  for (const z1 of VIZAG_ZONES) {
    matrix[z1.id] = {};
    for (const z2 of VIZAG_ZONES) {
      if (z1.id === z2.id) {
        matrix[z1.id][z2.id] = 0;
      } else {
        matrix[z1.id][z2.id] = calculateHaversineDistance(z1.centroid, z2.centroid);
      }
    }
  }
  return matrix;
}
